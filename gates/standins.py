"""The gate's stand-ins for other teams' services (ADR-031): on the gate and test clusters only,
never part of a release. Built here as one v1 List that `gate.py standins` applies.

- **S3: SeaweedFS** (`weed mini`): one pod, S3 on port 8333, the warehouse bucket created at
  start. Three identities from the gate's `.env` (generated by `gate.py secrets`), in an S3
  config file inside the Secret `seaweedfs-s3`: Polaris's key (`POLARIS_S3_*`), which may do
  everything, the smoke tests' key (`SMOKE_S3_*`), which may read, write and list the
  warehouse bucket only, and the backups' key (`POLARIS_BACKUP_S3_*`), the same on the backup
  bucket only (ADR-043), which `gate.py standins` creates once SeaweedFS is ready. Telemetry off. Ready only once the bucket exists: `mini`
  creates it after its services report ready, so its own health endpoint is not enough.
- **Policy endpoint: OPA**, serving gates/opa/policy.rego (package `polaris.authz`, the URL
  Polaris posts to, docs/contracts/polaris-opa-input.md) from the ConfigMap `opa-policy`.
- **The recorder** (ADR-034): gates/recorder/proxy.py from the ConfigMap `recorder-code`, on the
  pinned Python image, one listener per connection Polaris makes: 8181 to OPA, 8333 to
  SeaweedFS, 5432 to polaris-pg's read-write service in NS_CATALOG_POLARIS. It ends Polaris's
  TLS with the certificate the gate generates (Secret `recorder-tls`) and talks plain TCP to
  polaris-pg (ADR-035). On the gate, `.env` names the recorder, so every exchange with these
  three goes through it.
- **Metrics scraper: Prometheus** (ADR-046 §5), loading the scrape contract as
  gates/metrics.py fills it in (ConfigMap `prometheus-config`). It discovers pods in Polaris's
  namespace through a Role there that may only read pods. NS_STANDINS carries the label
  METRICS_NAMESPACE_LABEL names, so the stand-in crosses the release's own policies as the
  observability team's scraper would.

Ingress to NS_STANDINS is denied by default; the recorder takes connections from Polaris's
namespace, SeaweedFS, OPA and Prometheus from the gate's check pods, SeaweedFS and OPA also
from the recorder (ADR-048 §3, ADR-046 §4).

**Direct** (`manifests(..., direct=True)`, ADR-053 §4): for a stress install, which measures
Polaris and not the recorder. SeaweedFS and OPA also take connections from Polaris's namespace,
and each runs under the CPU limit given, so a stress run can tell when one of them is the limit.
Everything else is the List smoke applies.

Images are pinned by digest in gates/pins.json (`standin_images`). Everything lives in
`NS_STANDINS` but Prometheus's Role and RoleBinding, in Polaris's namespace; credentials reach
the cluster only inside the Secret, on stdin.
"""

import base64
import json

S3_PORT = 8333
OPA_PORT = 8181
OPA_PACKAGE_PATH = "/v1/data/polaris/authz"
RECORDER_READY_FILE = "/tmp/recorder-ready"
FILER_PORT = 8888
PG_PORT = 5432
PROMETHEUS_PORT = 9090
# The label every pod the gate starts to check things carries: in Polaris's namespace, those
# pods may reach the stand-ins directly (ADR-034, ADR-048 §3).
CHECK_LABEL = "lakehouse-gate/check"
# What gates/opa/policy.rego lets gate_stress do inside gate_stress_catalog (ADR-053): the
# actions Polaris 1.6.0's IcebergCatalogHandler asks about for the stress scenario's requests.
# `GET /v1/config` asks about none.
STRESS_ACTIONS = ("LIST_NAMESPACES", "CREATE_NAMESPACE", "LIST_TABLES", "CREATE_TABLE_DIRECT",
                  "LOAD_TABLE", "TABLE_EXISTS", "ADD_TABLE_SNAPSHOT", "SET_TABLE_SNAPSHOT_REF")
# The stand-ins a stress install points Polaris at directly, with their ports.
DIRECT = (("seaweedfs", S3_PORT), ("opa", OPA_PORT))


def b64(value):
    return base64.b64encode(value.encode("utf-8")).decode("ascii")


def load_cases(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)["cases"]


def _meta(name, namespace):
    return {"name": name, "namespace": namespace,
            "labels": {"app.kubernetes.io/name": name, "app.kubernetes.io/part-of": "standins"}}


def _deployment(name, namespace, container, volumes=()):
    labels = {"app.kubernetes.io/name": name}
    return {"apiVersion": "apps/v1", "kind": "Deployment", "metadata": _meta(name, namespace),
            "spec": {"replicas": 1, "selector": {"matchLabels": labels},
                     "template": {"metadata": {"labels": labels},
                                  "spec": {"containers": [{"name": name, **container}],
                                           "volumes": list(volumes)}}}}


def _service(name, namespace, port):
    return {"apiVersion": "v1", "kind": "Service", "metadata": _meta(name, namespace),
            "spec": {"selector": {"app.kubernetes.io/name": name},
                     "ports": [{"name": "http", "port": port, "targetPort": port}]}}


def _named(namespace):
    return {"namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": namespace}}}


def _app(name):
    return {"podSelector": {"matchLabels": {"app.kubernetes.io/name": name}}}


def _policy(name, namespace, pod_selector, ingress=None):
    spec = {"podSelector": pod_selector, "policyTypes": ["Ingress"]}
    if ingress is not None:
        spec["ingress"] = ingress
    return {"apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy",
            "metadata": _meta(name, namespace), "spec": spec}


def network_policies(env, direct=False):
    """NS_STANDINS's rows of ADR-048 §3 (from ADR-034, ADR-046 §4): default deny; the recorder
    from Polaris's namespace; SeaweedFS and OPA from the recorder and the gate's check pods, and
    with `direct` from Polaris's namespace too (ADR-053 §4); Prometheus from the gate's check
    pods."""
    ns, polaris = env["NS_STANDINS"], env["NS_CATALOG_POLARIS"]
    tcp = [{"protocol": "TCP", "port": p} for p in (OPA_PORT, S3_PORT, PG_PORT)]
    checks = {**_named(polaris),
              "podSelector": {"matchLabels": {CHECK_LABEL: "true"}}}
    policies = [_policy("default-deny-ingress", ns, {}),
                _policy("recorder", ns, _app("recorder")["podSelector"],
                        [{"ports": tcp, "from": [_named(polaris)]}])]
    for name, port in DIRECT:
        sources = [_app("recorder"), checks] + ([_named(polaris)] if direct else [])
        policies.append(_policy(name, ns, _app(name)["podSelector"], [{
            "ports": [{"protocol": "TCP", "port": port}], "from": sources}]))
    policies.append(_policy("prometheus", ns, _app("prometheus")["podSelector"], [{
        "ports": [{"protocol": "TCP", "port": PROMETHEUS_PORT}], "from": [checks]}]))
    return policies


def _namespace(env):
    """NS_STANDINS, with the metrics scraper's label from `.env` when there is one."""
    metadata = {"name": env["NS_STANDINS"]}
    key, _, value = env["METRICS_NAMESPACE_LABEL"].partition("=")
    if key:
        metadata["labels"] = {key: value}
    return {"apiVersion": "v1", "kind": "Namespace", "metadata": metadata}


def prometheus_objects(env, image, config):
    """The Prometheus stand-in: its config, ServiceAccount, Role and RoleBinding in Polaris's
    namespace (read pods only), Deployment and Service (ADR-046 §5)."""
    ns, polaris = env["NS_STANDINS"], env["NS_CATALOG_POLARIS"]
    rbac = "rbac.authorization.k8s.io"
    prometheus = {
        "image": image,
        "args": ["--config.file=/etc/prometheus/prometheus.yml",
                 "--storage.tsdb.path=/prometheus", "--storage.tsdb.retention.time=1d",
                 f"--web.listen-address=:{PROMETHEUS_PORT}"],
        "ports": [{"name": "http", "containerPort": PROMETHEUS_PORT}],
        "readinessProbe": {"httpGet": {"path": "/-/ready", "port": PROMETHEUS_PORT},
                           "periodSeconds": 5},
        "volumeMounts": [{"name": "config", "mountPath": "/etc/prometheus", "readOnly": True},
                         {"name": "data", "mountPath": "/prometheus"}],
    }
    deployment = _deployment("prometheus", ns, prometheus, [
        {"name": "config", "configMap": {"name": "prometheus-config"}},
        {"name": "data", "emptyDir": {}}])
    deployment["spec"]["template"]["spec"]["serviceAccountName"] = "prometheus"
    return [
        {"apiVersion": "v1", "kind": "ConfigMap", "metadata": _meta("prometheus-config", ns),
         "data": {"prometheus.yml": config}},
        {"apiVersion": "v1", "kind": "ServiceAccount", "metadata": _meta("prometheus", ns)},
        {"apiVersion": f"{rbac}/v1", "kind": "Role",
         "metadata": _meta("prometheus-discovery", polaris),
         "rules": [{"apiGroups": [""], "resources": ["pods"],
                    "verbs": ["get", "list", "watch"]}]},
        {"apiVersion": f"{rbac}/v1", "kind": "RoleBinding",
         "metadata": _meta("prometheus-discovery", polaris),
         "roleRef": {"apiGroup": rbac, "kind": "Role", "name": "prometheus-discovery"},
         "subjects": [{"kind": "ServiceAccount", "name": "prometheus", "namespace": ns}]},
        deployment,
        _service("prometheus", ns, PROMETHEUS_PORT),
    ]


def manifests(env, pins, policy_text, recorder_code, tls, prometheus_config, direct=False,
              cpu_limits=None):
    """A v1 List: the Namespace, then the Secrets, ConfigMaps, Deployments and Services.
    `tls` is the recorder's (certificate, key), PEM; `prometheus_config` the stand-in's
    prometheus.yml (gates/metrics.py). With `direct`, `cpu_limits` maps each name in DIRECT to
    its CPU limit (ADR-053 §4)."""
    if direct and set(cpu_limits or ()) != {name for name, _ in DIRECT}:
        raise ValueError(f"direct needs a CPU limit for each of {[n for n, _ in DIRECT]}")
    ns = env["NS_STANDINS"]
    svc = f"{ns}.svc.cluster.local"
    bucket = env["POLARIS_WAREHOUSE_BUCKET"]
    backup_bucket = env["POLARIS_BACKUP_BUCKET"]
    images = pins["standin_images"]
    s3_config = {"identities": [
        {"name": "polaris",
         "credentials": [{"accessKey": env["POLARIS_S3_ACCESS_KEY_ID"],
                          "secretKey": env["POLARIS_S3_SECRET_ACCESS_KEY"]}],
         "actions": ["Admin", "Read", "Write", "List", "Tagging"]},
        {"name": "smoke",
         "credentials": [{"accessKey": env["SMOKE_S3_ACCESS_KEY_ID"],
                          "secretKey": env["SMOKE_S3_SECRET_ACCESS_KEY"]}],
         "actions": [f"{action}:{bucket}" for action in ("Read", "Write", "List")]},
        {"name": "backup",
         "credentials": [{"accessKey": env["POLARIS_BACKUP_S3_ACCESS_KEY_ID"],
                          "secretKey": env["POLARIS_BACKUP_S3_SECRET_ACCESS_KEY"]}],
         "actions": [f"{action}:{backup_bucket}" for action in ("Read", "Write", "List")]},
    ]}
    seaweedfs = {
        "image": images["seaweedfs"]["image"],
        "args": ["mini", "-dir=/data", "-ip.bind=0.0.0.0", f"-s3.port={S3_PORT}",
                 f"-bucket={bucket}", "-master.telemetry=false", "-webdav=false",
                 "-admin.ui=false", "-s3.port.iceberg=0", "-s3.port.lance=0",
                 "-s3.config=/etc/seaweedfs/s3.json"],
        "ports": [{"name": "s3", "containerPort": S3_PORT}],
        "readinessProbe": {"exec": {"command": [
            "curl", "-sf", "-o", "/dev/null",
            f"http://127.0.0.1:{FILER_PORT}/buckets/{bucket}/"]},
            "periodSeconds": 5, "failureThreshold": 60},
        "volumeMounts": [{"name": "data", "mountPath": "/data"},
                         {"name": "s3-config", "mountPath": "/etc/seaweedfs", "readOnly": True}],
    }
    opa = {
        "image": images["opa"]["image"],
        "args": ["run", "--server", f"--addr=0.0.0.0:{OPA_PORT}", "--ignore=.*", "/policies"],
        "ports": [{"name": "http", "containerPort": OPA_PORT}],
        "readinessProbe": {"httpGet": {"path": "/health", "port": OPA_PORT},
                           "periodSeconds": 5},
        "volumeMounts": [{"name": "policy", "mountPath": "/policies", "readOnly": True}],
    }
    recorder = {
        "image": images["recorder"]["image"],
        "command": ["python3", "/recorder/proxy.py",
                    "--http", f"opa={OPA_PORT}:opa.{svc}:{OPA_PORT}",
                    "--http", f"s3={S3_PORT}:seaweedfs.{svc}:{S3_PORT}",
                    "--pg", (f"pg={PG_PORT}:polaris-pg-rw.{env['NS_CATALOG_POLARIS']}"
                             f".svc.cluster.local:{PG_PORT}"),
                    "--tls-cert", "/tls/tls.crt", "--tls-key", "/tls/tls.key",
                    "--ready-file", RECORDER_READY_FILE],
        "env": [{"name": "PYTHONUNBUFFERED", "value": "1"}],
        "ports": [{"name": name, "containerPort": port} for name, port in
                  (("opa", OPA_PORT), ("s3", S3_PORT), ("pg", PG_PORT))],
        # Not a connection to a listener: the recorder would relay it (gates/recorder/proxy.py).
        "readinessProbe": {"exec": {"command": ["test", "-f", RECORDER_READY_FILE]},
                           "periodSeconds": 2},
        "volumeMounts": [{"name": "code", "mountPath": "/recorder", "readOnly": True},
                         {"name": "tls", "mountPath": "/tls", "readOnly": True}],
    }
    if direct:
        for name, container in (("seaweedfs", seaweedfs), ("opa", opa)):
            container["resources"] = {"limits": {"cpu": cpu_limits[name]}}
    recorder_service = _service("recorder", ns, OPA_PORT)
    recorder_service["spec"]["ports"] = [
        {"name": name, "port": port, "targetPort": port}
        for name, port in (("opa", OPA_PORT), ("s3", S3_PORT), ("pg", PG_PORT))]
    return {"apiVersion": "v1", "kind": "List", "items": [
        _namespace(env),
        {"apiVersion": "v1", "kind": "Secret", "type": "Opaque",
         "metadata": _meta("seaweedfs-s3", ns),
         "data": {"s3.json": b64(json.dumps(s3_config))}},
        {"apiVersion": "v1", "kind": "ConfigMap", "metadata": _meta("opa-policy", ns),
         "data": {"policy.rego": policy_text}},
        _deployment("seaweedfs", ns, seaweedfs, [
            {"name": "data", "emptyDir": {}},
            {"name": "s3-config", "secret": {"secretName": "seaweedfs-s3"}}]),
        _service("seaweedfs", ns, S3_PORT),
        _deployment("opa", ns, opa, [{"name": "policy",
                                      "configMap": {"name": "opa-policy"}}]),
        _service("opa", ns, OPA_PORT),
        {"apiVersion": "v1", "kind": "Secret", "type": "kubernetes.io/tls",
         "metadata": _meta("recorder-tls", ns),
         "data": {"tls.crt": b64(tls[0]), "tls.key": b64(tls[1])}},
        {"apiVersion": "v1", "kind": "ConfigMap", "metadata": _meta("recorder-code", ns),
         "data": {"proxy.py": recorder_code}},
        _deployment("recorder", ns, recorder, [
            {"name": "code", "configMap": {"name": "recorder-code"}},
            {"name": "tls", "secret": {"secretName": "recorder-tls"}}]),
        recorder_service,
        *prometheus_objects(env, images["prometheus"]["image"], prometheus_config),
        *network_policies(env, direct),
    ]}
